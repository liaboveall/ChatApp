/** How many of the last used are kept and shown: two rows of the grid at its usual width. */
export const RECENT_EMOJI_MAX = 24

/** What was stored, as a list of emoji: anything that is not a list of short strings is nothing. */
export function parseRecentEmoji(raw: string | null): string[] {
  if (raw === null) return []
  try {
    const stored: unknown = JSON.parse(raw)
    if (!Array.isArray(stored)) return []
    return stored
      .filter(
        (item): item is string => typeof item === 'string' && item !== '' && item.length <= 16,
      )
      .slice(0, RECENT_EMOJI_MAX)
  } catch {
    return []
  }
}

/** The list with `emoji` used just now: it moves to the front, once, and the oldest falls off the end. */
export function withRecentEmoji(recent: readonly string[], emoji: string): string[] {
  return [emoji, ...recent.filter((item) => item !== emoji)].slice(0, RECENT_EMOJI_MAX)
}
